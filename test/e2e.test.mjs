// End-to-end tests against dist/cli.js. Run with `npm test`.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CLI = path.join(__dirname, "..", "dist", "cli.js");

// --- helpers ---

function cli(cwd, ...args) {
  const r = spawnSync("node", [CLI, ...args], { cwd, encoding: "utf-8" });
  return { status: r.status, out: r.stdout + r.stderr };
}

function ok(cwd, ...args) {
  const r = cli(cwd, ...args);
  assert.equal(r.status, 0, `expected exit 0 for \`${args.join(" ")}\`:\n${r.out}`);
  return r.out;
}

function fail(cwd, ...args) {
  const r = cli(cwd, ...args);
  assert.notEqual(r.status, 0, `expected non-zero exit for \`${args.join(" ")}\`:\n${r.out}`);
  return r.out;
}

function git(cwd, ...args) {
  const r = spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], {
    cwd,
    encoding: "utf-8",
  });
  assert.equal(r.status, 0, `git ${args.join(" ")} failed:\n${r.stdout}${r.stderr}`);
  return r.stdout.trim();
}

function tmp(name) {
  return fs.mkdtempSync(path.join(os.tmpdir(), `agentic-${name}-`));
}

function write(base, rel, content) {
  const p = path.join(base, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}

function read(base, rel) {
  return fs.readFileSync(path.join(base, rel), "utf-8");
}

function exists(base, rel) {
  try {
    fs.lstatSync(path.join(base, rel));
    return true;
  } catch {
    return false;
  }
}

function isLink(base, rel) {
  return exists(base, rel) && fs.lstatSync(path.join(base, rel)).isSymbolicLink();
}

function lock(project) {
  return JSON.parse(read(project, ".agentic/agentic.lock"));
}

/** Write a fixture harness. `v` selects content so tests can diff versions. */
function makeHarness(dir, v = 1) {
  // reset content but keep a .git dir if the fixture is a repo
  if (fs.existsSync(dir)) {
    for (const name of fs.readdirSync(dir)) {
      if (name !== ".git") fs.rmSync(path.join(dir, name), { recursive: true, force: true });
    }
  }
  write(dir, "harness.json", JSON.stringify({ name: "fixture", version: `${v}.0.0`, protocol: "2.0.0" }));
  write(dir, "rules/COMMON.md", `# Team rules v${v}\n\nRead .agentic/references/workflow.md.\n`);
  write(dir, "references/workflow.md", `# Workflow v${v}\n`);
  write(dir, "rules/PROJECT.md", "# Project (seed)\n");
  write(dir, "skills/commit/SKILL.md", `---\nname: commit\ndescription: commit v${v}\n---\n# commit\n`);
  if (v >= 2) write(dir, "skills/review/SKILL.md", "---\nname: review\ndescription: review\n---\n# review\n");
  if (v === 1) write(dir, "agents/reviewer.md", "---\nname: reviewer\ndescription: reviews\n---\nReview carefully.\n");
  write(
    dir,
    "mcps.json",
    JSON.stringify(
      {
        mcpServers: {
          browser: { command: "npx", args: ["@browsermcp/mcp@latest"] },
          jira: { type: "http", url: "https://mcp.example.com/mcp" },
          ...(v === 1 ? { lsp: { command: "npx", args: ["lsmcp"], env: { TOKEN: "${LSP_TOKEN}" } } } : {}),
        },
      },
      null,
      2
    )
  );
  return dir;
}

function freshProject(name) {
  const project = tmp(name);
  git(project, "init", "-q", "-b", "main");
  write(project, "README.md", "# app\n");
  return project;
}


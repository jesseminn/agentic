test("mcp add refuses literal secrets and marks ownership", () => {
  const harness = makeHarness(tmp("harness"));
  const project = freshProject("proj");
  ok(project, "install", harness);
  ok(project, "link", "antigravity");

  const out = fail(project, "mcp", "add", "gh", "npx", "mcp-github", "--env", "GITHUB_TOKEN=ghp_abc");
  assert.match(out, /must be \$\{NAME\} references/);

  ok(project, "mcp", "add", "gh", "npx", "mcp-github", "--env", "GITHUB_TOKEN=${GITHUB_TOKEN}");
  const list = ok(project, "mcp", "list");
  assert.match(list, /gh: npx mcp-github  \[project\]/);
  assert.match(list, /browser: .*\[harness\]/);
  const agy = JSON.parse(read(project, ".agents/mcp_config.json"));
  assert.ok("gh" in agy.mcpServers, "propagated to linked platform");

  const warn = cli(project, "mcp", "remove", "browser");
  assert.equal(warn.status, 0);
  assert.match(warn.out, /harness-owned/);

  // a harness with a literal secret is rejected at install
  const bad = makeHarness(tmp("bad"));
  write(bad, "mcps.json", JSON.stringify({ mcpServers: { x: { command: "x", env: { K: "literal" } } } }));
  const p2 = freshProject("proj2");
  assert.match(fail(p2, "install", bad), /x\.env\.K/);
});


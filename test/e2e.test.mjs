test("install from a git URL records the commit; update re-clones from the lock", () => {
  const hdir = makeHarness(tmp("harness"), 1);
  git(hdir, "init", "-q", "-b", "main");
  git(hdir, "add", "-A");
  git(hdir, "commit", "-qm", "v1");
  const sha1 = git(hdir, "rev-parse", "HEAD");

  const project = freshProject("proj");
  ok(project, "install", `file://${hdir}#main`);
  let l = lock(project);
  assert.equal(l.harness.source, `file://${hdir}`);
  assert.equal(l.harness.ref, "main");
  assert.equal(l.harness.commit, sha1);

  makeHarness(hdir, 2);
  git(hdir, "add", "-A");
  git(hdir, "commit", "-qm", "v2");
  const sha2 = git(hdir, "rev-parse", "HEAD");

  ok(project, "update");
  l = lock(project);
  assert.equal(l.harness.commit, sha2);
  assert.equal(l.harness.version, "2.0.0");

  // a commit sha as ref goes through the full-clone fallback
  const p2 = freshProject("proj2");
  ok(p2, "install", `file://${hdir}#${sha1}`);
  assert.equal(lock(p2).harness.version, "1.0.0");
});

test("install refuses to overwrite differing local content, adopts identical content", () => {
  const harness = makeHarness(tmp("harness"));
  const project = freshProject("proj");
  ok(project, "init");
  // init wrote its own rules/COMMON.md stub → conflict
  const out = fail(project, "install", harness);
  assert.match(out, /rules\/COMMON\.md/);
  assert.match(out, /Nothing was written/);
  assert.ok(!exists(project, ".agentic/skills/commit"));

  // identical content is adopted (the v0.2 migration path)
  fs.copyFileSync(path.join(harness, "rules/COMMON.md"), path.join(project, ".agentic/rules/COMMON.md"));
  fs.cpSync(path.join(harness, "skills/commit"), path.join(project, ".agentic/skills/commit"), { recursive: true });
  const out2 = ok(project, "install", harness);
  assert.match(out2, /2 already present, adopted/);
});

test("v0.2 whole-directory symlinks migrate to per-entry links", () => {
  const harness = makeHarness(tmp("harness"));
  const project = freshProject("proj");
  // replicate a v0.2 install: content in .agentic/, whole-dir links, ignored derived files
  fs.cpSync(harness, path.join(project, ".agentic"), { recursive: true });
  fs.unlinkSync(path.join(project, ".agentic/harness.json"));
  fs.renameSync(path.join(project, ".agentic/mcps.json"), path.join(project, ".agentic/.mcp.json"));
  fs.renameSync(path.join(project, ".agentic/rules/COMMON.md"), path.join(project, ".agentic/RULES.md"));
  fs.renameSync(path.join(project, ".agentic/rules/PROJECT.md"), path.join(project, ".agentic/PROJECT.md"));
  fs.symlinkSync(".agentic/RULES.md", path.join(project, "CLAUDE.md"));
  fs.symlinkSync(".agentic/.mcp.json", path.join(project, ".mcp.json"));
  fs.mkdirSync(path.join(project, ".claude"));
  fs.symlinkSync("../.agentic/skills", path.join(project, ".claude/skills"));
  fs.symlinkSync("../.agentic/agents", path.join(project, ".claude/agents"));
  write(
    project,
    ".gitignore",
    "node_modules/\n\n# Claude Code (derived from .agentic/)\n/CLAUDE.md\n/.mcp.json\n.claude/skills\n.claude/agents\n.claude/settings.local.json\n"
  );

  // no lock + the old paths ⇒ protocol 1.0: install migrates first, then adopts everything as identical
  const inst = ok(project, "install", harness);
  assert.match(inst, /Migrated \.agentic\/ from protocol 1\.0\.0 to 2\.0\.0/);
  assert.match(inst, /RULES\.md → rules\/COMMON\.md/);
  assert.match(inst, /PROJECT\.md → rules\/PROJECT\.md/);
  assert.match(inst, /4 harness files \(7 already present, adopted\)/, "4 files + 3 MCP keys, all identical");
  assert.equal(lock(project).protocol, "2.0.0");
  const out = ok(project, "link", "claude");
  assert.match(out, /CLAUDE\.md \(whole-file symlink from v0\.2\)/);
  assert.match(out, /\.claude\/skills \(whole-directory symlink from v0\.2\)/);
  assert.ok(!isLink(project, "CLAUDE.md"));
  assert.ok(!isLink(project, ".claude/skills"));
  assert.ok(isLink(project, ".claude/skills/commit"));
  assert.ok(isLink(project, ".claude/agents/reviewer.md"));
  const ignore = read(project, ".gitignore");
  assert.doesNotMatch(ignore, /\/CLAUDE\.md/);
  assert.match(ignore, /node_modules\//);
  assert.match(ignore, /\.claude\/worktrees\//);
});

test("uninstall removes harness content, keeps project content and modified files, prunes links", () => {
  const harness = makeHarness(tmp("harness"));
  const project = freshProject("proj");
  ok(project, "install", harness);
  ok(project, "link", "claude");
  write(project, ".agentic/skills/my-skill/SKILL.md", "---\nname: my-skill\n---\n");
  write(project, ".agentic/references/workflow.md", "edited\n");
  ok(project, "link", "claude");

  const out = ok(project, "uninstall");
  assert.match(out, /references\/workflow\.md \(modified locally\)/);
  assert.ok(!exists(project, ".agentic/rules/COMMON.md"));
  assert.ok(!exists(project, ".agentic/skills/commit"));
  assert.ok(!exists(project, ".agentic/agents/reviewer.md"));
  assert.ok(exists(project, ".agentic/rules") && exists(project, ".agentic/agents"), "standard top-level dirs stay");
  assert.ok(exists(project, ".agentic/references/workflow.md"), "modified file kept");
  assert.ok(exists(project, ".agentic/skills/my-skill/SKILL.md"));
  assert.ok(exists(project, ".agentic/rules/PROJECT.md"));
  assert.ok(!exists(project, ".claude/skills/commit"), "link pruned");
  assert.ok(isLink(project, ".claude/skills/my-skill"));
  assert.ok(!exists(project, ".claude/agents/reviewer.md"));

  const l = lock(project);
  assert.equal(l.harness, null);
  assert.deepEqual(l.files, {});
  assert.deepEqual(l.platforms, ["claude"]);
  assert.deepEqual(JSON.parse(read(project, ".agentic/.mcp.json")).mcpServers, {});

  // re-install: the kept edit now collides with the harness file
  assert.match(fail(project, "install", harness), /references\/workflow\.md/);
  fs.unlinkSync(path.join(project, ".agentic/references/workflow.md"));
  ok(project, "install", harness);
  assert.ok(isLink(project, ".claude/skills/commit"), "re-install re-links recorded platforms");
});

